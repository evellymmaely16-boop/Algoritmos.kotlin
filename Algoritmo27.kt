* Objetivo: Testar o funcionamento dos operadores de incremento (++) e decremento (--).
*/
fun main() {
   var x = 2
   var y = 5
   println("x = $x")
   x++
   println("\ny = $y")
   y--
   println("\nnovo valor de x = $x")
   println("novo valor de y = $y")
}


